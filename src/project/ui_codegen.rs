use std::path::{Path, PathBuf};

const HEADER: &str = "// Generated by Enigma UI Editor. Changes will be overwritten.\n";
const RUNTIME: &str = include_str!("../ui_runtime.rs");
const MAX_SCREEN_TEXTURE_BYTES: usize = 128 * 1024 * 1024;
const MAX_EXPORT_TEXTURE_BYTES: usize = 512 * 1024 * 1024;

const KEYWORDS: &[&str] = &[
    "abstract", "as", "async", "await", "become", "box", "break", "const", "continue", "crate",
    "do", "dyn", "else", "enum", "extern", "false", "final", "fn", "for", "gen", "if", "impl",
    "in", "let", "loop", "macro", "match", "mod", "move", "mut", "override", "priv", "pub", "ref",
    "return", "self", "static", "struct", "super", "trait", "true", "try", "type", "typeof",
    "unsafe", "unsized", "use", "virtual", "where", "while", "yield",
];

fn words(name: &str) -> Vec<String> {
    let mut words = Vec::new();
    let mut word = String::new();
    let mut previous = None;
    let mut chars = name.chars().peekable();
    while let Some(c) = chars.next() {
        if !c.is_ascii_alphanumeric() {
            if !word.is_empty() {
                words.push(std::mem::take(&mut word));
            }
            previous = None;
            continue;
        }
        if c.is_ascii_uppercase()
            && previous.is_some_and(|p: char| {
                p.is_ascii_lowercase()
                    || (p.is_ascii_uppercase()
                        && chars.peek().is_some_and(char::is_ascii_lowercase))
            })
        {
            words.push(std::mem::take(&mut word));
        }
        word.push(c.to_ascii_lowercase());
        previous = Some(c);
    }
    if !word.is_empty() {
        words.push(word);
    }
    words
}

pub fn module_name(screen: &UiScreen) -> String {
    let mut name = words(&screen.name).join("_");
    name.truncate(96);
    if name.is_empty() {
        name = "screen".into();
    } else if name.starts_with(|c: char| c.is_ascii_digit()) {
        name.insert_str(0, "screen_");
    }
    // Reserve the shared module name and Windows device names.
    let device = ["con", "prn", "aux", "nul"].contains(&name.as_str())
        || (name.len() == 4
            && (name.starts_with("com") || name.starts_with("lpt"))
            && matches!(name.as_bytes()[3], b'1'..=b'9'));
    if KEYWORDS.contains(&name.as_str()) || name == "runtime" || device {
        name.push_str("_screen");
    }
    name
}

pub fn class_name(screen: &UiScreen) -> String {
    let mut name = String::new();
    for word in words(&screen.name) {
        let mut chars = word.chars();
        if let Some(c) = chars.next() {
            name.push(c.to_ascii_uppercase());
        }
        name.extend(chars);
    }
    name.truncate(96);
    if name.is_empty() || name.starts_with(|c: char| c.is_ascii_digit()) {
        name.insert_str(0, "Screen");
    }
    name.push_str("Ui");
    name
}

pub fn source(screen: &UiScreen) -> Result<String, String> {
    screen.validate()?;
    let class = class_name(screen);
    let json =
        serde_json::to_string(screen).map_err(|err| format!("Cannot encode screen: {err}"))?;
    let state_key = format!("enigma.generated_ui.screen:{}", screen.id);
    let install_key = format!("enigma.generated_ui.installed:{}", screen.id);
    let (texture_field, texture_default, texture_loader, load_call) = embedded_textures(screen);
    // Debug formatting for strings creates escaped Rust literals, including
    // quotes/backslashes in the JSON and arbitrary authored identifiers.
    Ok(format!(
        r#"{HEADER}use super::runtime::*;
use enigma_3d::{{ui as egui, AppState}};
use std::sync::Arc;

pub struct {class} {{
    pub screen: UiScreen,
    pub data: UiData,
    pub visible: bool,
    pub textures: UiTextures,
{texture_field}
}}

impl Default for {class} {{
    fn default() -> Self {{
        let screen: UiScreen = serde_json::from_str({json:?})
            .expect("generated layout was validated during export");
        let data = screen.sample_data.clone();
        Self {{ screen, data, visible: true, textures: UiTextures::default(), {texture_default} }}
    }}
}}

impl {class} {{
    pub const STATE_KEY: &'static str = {state_key:?};
    const INSTALL_KEY: &'static str = {install_key:?};
{texture_loader}

    pub fn draw(&mut self, ctx: &egui::Context) -> Vec<UiEvent> {{
        if !self.visible {{
            return Vec::new();
        }}
{load_call}
        // Use a transparent child UI on egui's background layer. A full-size
        // Area would register a hit target even outside the authored widgets.
        let rect = ctx.screen_rect();
        let mut ui = egui::Ui::new(
            ctx.clone(),
            egui::LayerId::background(),
            egui::Id::new(Self::STATE_KEY),
            rect,
            rect,
        );
        draw_screen_with_textures(&mut ui, &self.screen, &mut self.data, rect, true, &self.textures)
    }}

    pub fn install<F: Fn(UiEvent, &mut AppState) + 'static>(app: &mut AppState, on_event: F) {{
        if app.get_state_data_value::<bool>(Self::INSTALL_KEY).is_some() {{
            return;
        }}
        if app.get_state_data_value::<Self>(Self::STATE_KEY).is_none() {{
            app.set_state_data_value(Self::STATE_KEY, Box::new(Self::default()));
        }}
        app.set_state_data_value(Self::INSTALL_KEY, Box::new(true));
        app.inject_gui(Arc::new(move |ctx, app| {{
            let events = app.get_state_data_value_mut::<Self>(Self::STATE_KEY)
                .map(|screen| screen.draw(ctx))
                .unwrap_or_default();
            for event in events {{
                on_event(event, app);
            }}
        }}));
    }}
}}
"#
    ))
}

fn texture_filename(module: &str, index: usize) -> String {
    format!("{module}.texture.{index}.rgba")
}

fn embedded_textures(screen: &UiScreen) -> (&'static str, &'static str, String, &'static str) {
    if screen.textures.is_empty() {
        return ("", "", String::new(), "");
    }
    let module = module_name(screen);
    let mut entries = String::new();
    for (index, key) in screen.textures.keys().enumerate() {
        let file = texture_filename(&module, index);
        writeln!(
            &mut entries,
            "            ({key:?}, include_bytes!({file:?}) as &[u8]),"
        )
        .unwrap();
    }
    let header_len = HEADER.len();
    let loader = format!(
        r#"
    fn load_embedded_textures(&mut self, ctx: &egui::Context) {{
        if self.embedded_textures_loaded {{
            return;
        }}
        self.embedded_textures_loaded = true;
        for (key, bytes) in [
{entries}        ] {{
            if self.textures.contains(key) {{
                continue;
            }}
            let Some((size, rgba)) = bytes.get({header_len}..).and_then(|data| {{
                (data.len() >= 8).then(|| data.split_at(8))
            }}) else {{
                eprintln!("Invalid embedded UI texture: {{key}}");
                continue;
            }};
            let width = u32::from_le_bytes(size[..4].try_into().unwrap()) as usize;
            let height = u32::from_le_bytes(size[4..].try_into().unwrap()) as usize;
            if let Err(err) = self.textures.insert_rgba(ctx, key, [width, height], rgba) {{
                eprintln!("{{err}}");
            }}
        }}
    }}
"#
    );
    (
        "    embedded_textures_loaded: bool,",
        "embedded_textures_loaded: false,",
        loader,
        "        self.load_embedded_textures(ctx);",
    )
}

pub fn generate(root: &Path, screens: &[UiScreen]) -> Result<Vec<PathBuf>, String> {
    let mut modules = BTreeSet::new();
    let mut classes = BTreeSet::new();
    let mut ids = BTreeSet::new();
    let dir = root.join("src/generated_ui");
    let mut files = Vec::with_capacity(screens.len() + 2);
    let mut exports = format!("{HEADER}pub mod runtime;\n");
    let mut export_texture_bytes = 0;
    for screen in screens {
        let module = module_name(screen);
        let class = class_name(screen);
        if !modules.insert(module.clone())
            || !classes.insert(class.clone())
            || !ids.insert(&screen.id)
        {
            return Err(format!(
                "Screen {:?} has a duplicate Rust module, class, or screen ID.",
                screen.name
            ));
        }
        let wrapper = source(screen)?;
        let mut screen_texture_bytes = 0;
        for (index, relative) in screen.textures.values().enumerate() {
            let texture = ui_assets::load(root, relative)?;
            screen_texture_bytes += texture.rgba.len();
            export_texture_bytes += texture.rgba.len();
            if screen_texture_bytes > MAX_SCREEN_TEXTURE_BYTES
                || export_texture_bytes > MAX_EXPORT_TEXTURE_BYTES
            {
                return Err("UI export allows up to 128 MiB of decoded textures per screen and 512 MiB per export.".into());
            }
            let mut contents = Vec::with_capacity(HEADER.len() + 8 + texture.rgba.len());
            contents.extend_from_slice(HEADER.as_bytes());
            for side in texture.size {
                contents.extend_from_slice(&(side as u32).to_le_bytes());
            }
            contents.extend_from_slice(&texture.rgba);
            files.push((dir.join(texture_filename(&module, index)), contents));
        }
        files.push((dir.join(format!("{module}.rs")), wrapper.into_bytes()));
        exports.push_str(&format!("pub mod {module};\npub use {module}::{class};\n"));
    }
    files.push((
        dir.join("runtime.rs"),
        format!("{HEADER}{RUNTIME}").into_bytes(),
    ));
    // Write the module declaration last so it only refers to completed files.
    files.push((dir.join("mod.rs"), exports.into_bytes()));

    let source_dir = root.join("src");
    check_directory(root, true)?;
    check_directory(&source_dir, false)?;
    check_directory(&dir, false)?;
    for (path, _) in &files {
        check_owned_file(path)?;
    }

    fs::create_dir_all(&dir).map_err(|err| io_error(&dir, err))?;
    let mut staged = Vec::with_capacity(files.len());
    for (i, (path, contents)) in files.iter().enumerate() {
        staged.push(StagedFile::new(&dir, i, path, contents)?);
    }
    let mut paths = Vec::with_capacity(files.len());
    for file in &mut staged {
        // Recheck before replacing in case a file appeared while staging.
        check_directory(&source_dir, true)?;
        check_directory(&dir, true)?;
        check_owned_file(&file.target)?;
        fs::rename(&file.path, &file.target).map_err(|err| io_error(&file.target, err))?;
        file.committed = true;
        paths.push(file.target.clone());
    }
    Ok(paths)
}

fn check_directory(path: &Path, required: bool) -> Result<(), String> {
    match fs::symlink_metadata(path) {
        Ok(meta) if meta.is_dir() => Ok(()),
        Ok(_) => Err(format!("Expected a real directory at {}.", path.display())),
        Err(err) if err.kind() == io::ErrorKind::NotFound && !required => Ok(()),
        Err(err) => Err(io_error(path, err)),
    }
}

fn check_owned_file(path: &Path) -> Result<(), String> {
    match fs::symlink_metadata(path) {
        Ok(meta) if meta.is_file() => {
            let mut header = [0; HEADER.len()];
            let mut file = File::open(path).map_err(|err| io_error(path, err))?;
            match file.read_exact(&mut header) {
                Ok(()) if header == HEADER.as_bytes() => Ok(()),
                Ok(()) => Err(refused(path)),
                Err(err) if err.kind() == io::ErrorKind::UnexpectedEof => Err(refused(path)),
                Err(err) => Err(io_error(path, err)),
            }
        }
        Ok(_) => Err(refused(path)),
        Err(err) if err.kind() == io::ErrorKind::NotFound => Ok(()),
        Err(err) => Err(io_error(path, err)),
    }
}

fn refused(path: &Path) -> String {
    format!(
        "Refusing to replace an unmanaged file or link at {}.",
        path.display()
    )
}

fn io_error(path: &Path, err: io::Error) -> String {
    format!("{}: {err}", path.display())
}

struct StagedFile {
    path: PathBuf,
    target: PathBuf,
    committed: bool,
}

impl StagedFile {
    fn new(dir: &Path, index: usize, target: &Path, contents: &[u8]) -> Result<Self, String> {
        let mut attempt = 0;
        let (path, mut file) = loop {
            let path = dir.join(format!(
                ".enigma-ui-{}-{index}-{attempt}.tmp",
                std::process::id()
            ));
            match OpenOptions::new().write(true).create_new(true).open(&path) {
                Ok(file) => break (path, file),
                Err(err) if err.kind() == io::ErrorKind::AlreadyExists && attempt < 100 => {
                    attempt += 1
                }
                Err(err) => return Err(io_error(&path, err)),
            }
        };
        let staged = Self {
            path,
            target: target.into(),
            committed: false,
        };
        file.write_all(contents)
            .map_err(|err| io_error(&staged.path, err))?;
        Ok(staged)
    }
}

impl Drop for StagedFile {
    fn drop(&mut self) {
        if !self.committed {
            let _ = fs::remove_file(&self.path);
        }
    }
}
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn empty_export_has_an_importable_module_and_runtime() {
        let root = tempfile::tempdir().unwrap();
        std::fs::create_dir(root.path().join("src")).unwrap();
        assert_eq!(generate(root.path(), &[]).unwrap().len(), 2);
        assert!(root.path().join("src/generated_ui/mod.rs").is_file());
        assert!(root.path().join("src/generated_ui/runtime.rs").is_file());
    }

    #[test]
    fn class_collision_is_rejected_before_touching_output() {
        let root = tempfile::tempdir().unwrap();
        std::fs::create_dir(root.path().join("src")).unwrap();
        let screens = [UiScreen::new("room 12", "a"), UiScreen::new("room12", "b")];
        assert!(generate(root.path(), &screens).is_err());
        assert!(!root.path().join("src/generated_ui").exists());
    }

    #[test]
    fn handwritten_file_is_never_overwritten_or_partially_exported() {
        let root = tempfile::tempdir().unwrap();
        let dir = root.path().join("src/generated_ui");
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(dir.join("test.rs"), "handwritten").unwrap();
        assert!(generate(root.path(), &[UiScreen::new("Test", "a")]).is_err());
        assert_eq!(
            std::fs::read_to_string(dir.join("test.rs")).unwrap(),
            "handwritten"
        );
        assert!(!dir.join("mod.rs").exists());
        assert!(!dir.join("runtime.rs").exists());
    }

    #[test]
    fn texture_export_preflights_sources_and_binary_ownership() {
        let root = tempfile::tempdir().unwrap();
        let dir = root.path().join("src/generated_ui");
        let resources = root.path().join("src/resources");
        fs::create_dir_all(&dir).unwrap();
        fs::create_dir_all(&resources).unwrap();
        let mut screen = UiScreen::new("Test", "a");
        screen.textures.insert("icon".into(), "icon.png".into());
        assert!(generate(root.path(), std::slice::from_ref(&screen)).is_err());
        assert_eq!(fs::read_dir(&dir).unwrap().count(), 0);

        image::RgbaImage::from_pixel(1, 1, image::Rgba([11, 22, 33, 255]))
            .save(resources.join("icon.png"))
            .unwrap();
        let binary = dir.join("test.texture.0.rgba");
        fs::write(&binary, b"handwritten binary").unwrap();
        assert!(generate(root.path(), std::slice::from_ref(&screen)).is_err());
        assert_eq!(fs::read(&binary).unwrap(), b"handwritten binary");
        assert!(!dir.join("test.rs").exists());

        fs::remove_file(&binary).unwrap();
        assert!(generate(root.path(), std::slice::from_ref(&screen))
            .unwrap()
            .contains(&binary));
        let embedded = fs::read(&binary).unwrap();
        assert!(embedded.starts_with(HEADER.as_bytes()));
        assert!(embedded.ends_with(&[11, 22, 33, 255]));
        assert!(generate(root.path(), &[screen]).is_ok());
    }

    #[cfg(unix)]
    #[test]
    fn symlinked_destinations_are_rejected_before_other_files_are_written() {
        let root = tempfile::tempdir().unwrap();
        let dir = root.path().join("src/generated_ui");
        std::fs::create_dir_all(&dir).unwrap();
        std::os::unix::fs::symlink(root.path().join("missing"), dir.join("test.rs")).unwrap();
        assert!(generate(root.path(), &[UiScreen::new("Test", "a")]).is_err());
        assert!(!dir.join("mod.rs").exists());
    }
}
