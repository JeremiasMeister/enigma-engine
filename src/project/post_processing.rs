//! Compile project-owned Rust effects into an editor executable using the same native trait.
use crate::editor::state::{EditorRoot, Modal, ProjectState};
use enigma_3d::AppState;
use std::fs;
use std::path::{Path, PathBuf};

const MARKER: &str = "Generated by Enigma project effects";

fn check_path(root: &Path, path: &Path) -> Result<(), String> {
    let relative = path.strip_prefix(root).map_err(|e| e.to_string())?;
    let mut current = root.to_path_buf();
    for part in relative.components() {
        current.push(part);
        if let Ok(meta) = fs::symlink_metadata(&current) {
            if meta.file_type().is_symlink() {
                return Err(format!(
                    "Cannot generate through symlink {}",
                    current.display()
                ));
            }
        }
    }
    Ok(())
}

/// Create an example only when the project has no registration module yet.
pub fn scaffold(root: &Path) -> Result<(), String> {
    let module = root.join("src/postprocessing/mod.rs");
    check_path(root, &module)?;
    if module.exists() {
        return Ok(());
    }
    let shader = root.join("src/postprocessing/tint.glsl");
    check_path(root, &shader)?;
    if shader.exists() {
        return Err(
            "A tint.glsl already exists; create your registration module manually to preserve it."
                .into(),
        );
    }
    fs::create_dir_all(module.parent().unwrap()).map_err(|e| e.to_string())?;
    fs::write(
        shader,
        include_str!("../resources/postprocessing_tint.glsl.resource"),
    )
    .map_err(|e| e.to_string())?;
    fs::write(
        module,
        include_str!("../resources/postprocessing.rs.resource"),
    )
    .map_err(|e| e.to_string())?;
    Ok(())
}

fn absolute_dependency_paths(item: &mut toml_edit::Item, root: &Path) -> Result<(), String> {
    if let Some(table) = item.as_table_like_mut() {
        for (_, dependency) in table.iter_mut() {
            if dependency.get("workspace").and_then(|v| v.as_bool()) == Some(true) {
                return Err("Project editor dependencies must be explicit; workspace-inherited dependencies are not supported yet.".into());
            }
            if let Some(path) = dependency
                .get("path")
                .and_then(|v| v.as_str())
                .map(str::to_owned)
            {
                let path = Path::new(&path);
                if path.is_relative() {
                    dependency["path"] =
                        toml_edit::value(root.join(path).to_string_lossy().as_ref());
                }
            }
        }
    }
    Ok(())
}

/// Generate a separate host package; the project's Cargo.toml and source remain user-owned.
pub fn prepare_editor(root: &Path) -> Result<PathBuf, String> {
    let root = root.canonicalize().map_err(|e| e.to_string())?;
    let module = root.join("src/postprocessing/mod.rs");
    if !module.is_file() {
        return Err("Create src/postprocessing/mod.rs first.".into());
    }
    let project: toml_edit::DocumentMut = fs::read_to_string(root.join("Cargo.toml"))
        .map_err(|e| e.to_string())?
        .parse()
        .map_err(|e: toml_edit::TomlError| e.to_string())?;
    let editor: toml_edit::DocumentMut = include_str!("../../Cargo.toml")
        .parse()
        .map_err(|e: toml_edit::TomlError| e.to_string())?;
    let mut host = toml_edit::DocumentMut::new();
    host["package"]["name"] = toml_edit::value("enigma-project-editor");
    host["package"]["version"] = toml_edit::value("0.0.0");
    host["package"]["edition"] = toml_edit::value(
        project["package"]
            .get("edition")
            .and_then(|e| e.as_str())
            .unwrap_or("2021"),
    );
    host["workspace"] = toml_edit::Item::Table(toml_edit::Table::new());
    for section in ["dependencies", "features", "patch", "target"] {
        if let Some(item) = project.get(section) {
            host[section] = item.clone();
        }
    }
    absolute_dependency_paths(&mut host["dependencies"], &root)?;
    if let Some(targets) = host.get_mut("target").and_then(|i| i.as_table_like_mut()) {
        for (_, target) in targets.iter_mut() {
            if let Some(dependencies) = target.get_mut("dependencies") {
                absolute_dependency_paths(dependencies, &root)?;
            }
        }
    }
    if let Some(patches) = host.get_mut("patch").and_then(|i| i.as_table_like_mut()) {
        for (_, patch) in patches.iter_mut() {
            absolute_dependency_paths(patch, &root)?;
        }
    }
    // Both host and project module must use the exact same enigma-3d/glium types.
    host["dependencies"]["enigma-3d"] = editor["dependencies"]["enigma-3d"].clone();
    host["dependencies"]["glium"] = editor["dependencies"]["glium"].clone();
    host["dependencies"]["enigma-engine"]["path"] = toml_edit::value(env!("CARGO_MANIFEST_DIR"));
    if let Some(patches) = editor.get("patch").and_then(|i| i.as_table_like()) {
        for (source, patch) in patches.iter() {
            if let Some(engine) = patch.get("enigma-3d") {
                host["patch"][source]["enigma-3d"] = engine.clone();
            }
        }
    }
    let main = format!("// {MARKER}\n#[path = {module:?}]\nmod project_postprocessing;\nfn main() {{\n    enigma_engine::run(Some({project:?}), Some(project_postprocessing::register));\n}}\n", module = module.to_string_lossy(), project = root.join("enigma_project.json").to_string_lossy());
    let dir = root.join(".enigma/editor");
    let files = [
        (dir.join("Cargo.toml"), format!("# {MARKER}\n{host}")),
        (dir.join("src/main.rs"), main),
    ];
    for (path, _) in &files {
        check_path(&root, path)?;
        if path.exists()
            && !fs::read_to_string(path)
                .map_err(|e| e.to_string())?
                .lines()
                .next()
                .unwrap_or("")
                .contains(MARKER)
        {
            return Err(format!(
                "Refusing to overwrite handwritten file {}",
                path.display()
            ));
        }
    }
    fs::create_dir_all(dir.join("src")).map_err(|e| e.to_string())?;
    for (path, text) in files {
        fs::write(path, text).map_err(|e| e.to_string())?;
    }
    let lock = dir.join("Cargo.lock");
    check_path(&root, &lock)?;
    if !lock.exists() {
        let project_lock = root.join("Cargo.lock");
        let editor_lock = Path::new(env!("CARGO_MANIFEST_DIR")).join("Cargo.lock");
        let seed = if project_lock.is_file() {
            project_lock
        } else {
            editor_lock
        };
        if seed.is_file() {
            fs::copy(seed, lock).map_err(|e| e.to_string())?;
        }
    }
    Ok(dir)
}

pub fn draw_project_controls(ui: &mut egui::Ui, app: &mut AppState) {
    let Some(project) = app
        .get_state_data_value::<EditorRoot>("editor")
        .and_then(|r| r.project.as_ref())
    else {
        return;
    };
    let root = PathBuf::from(&project.root_path);
    let exists = root.join("src/postprocessing/mod.rs").is_file();
    ui.label("Custom Rust effects");
    ui.weak("Register native effects in src/postprocessing/mod.rs.");
    let mut error = None;
    if !exists && ui.button("Create example effect").clicked() {
        error = scaffold(&root).err();
    }
    let busy = crate::editor::actions::is_busy(app)
        || app
            .get_state_data_value::<EditorRoot>("editor")
            .is_some_and(|r| r.editor.save_job.is_some());
    if ui.add_enabled(exists && !busy, egui::Button::new("Load project effects")).on_hover_text("Save and compile an editor with this project's Rust effects. Opens a project editor window when ready.").clicked() {
        let result = (|| {
            if let Some(root) = app.get_state_data_value_mut::<EditorRoot>("editor") {
                root.editor.code_editor.save_project(&PathBuf::from(&root.project.as_ref().unwrap().root_path)).map_err(|e| e.to_string())?;
            }
            let project = app.get_state_data_value::<EditorRoot>("editor").and_then(|r| r.project.clone()).unwrap();
            crate::project::scene::save_active(&project, app).map_err(|e| format!("Save scene: {e:?}"))?;
            crate::project::try_save_project(app).map_err(|e| e.to_string())?;
            prepare_editor(Path::new(&project.root_path))
        })();
        match result {
            Ok(directory) => {
                if let Some(editor) = app.get_state_data_value_mut::<EditorRoot>("editor") {
                    editor.editor.project_editor_handoff = Some(root.join("enigma_project.json").to_string_lossy().into_owned());
                }
                let host = ProjectState::new("Project editor".into(), directory.to_string_lossy().into_owned());
                crate::editor::actions::start_cargo(app, &host, "Project Editor", vec!["run".into()]);
            }
            Err(e) => error = Some(e),
        }
    }
    ui.weak("For games, call postprocessing::register before loading the scene. New projects include this hook.");
    if let Some(error) = error {
        if let Some(root) = app.get_state_data_value_mut::<EditorRoot>("editor") {
            root.editor.modal = Some(Modal::ImportError(error));
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn scaffold_preserves_custom_source_and_prepares_project_dependencies() {
        let tmp = tempfile::tempdir().unwrap();
        fs::write(tmp.path().join("Cargo.toml"), "[package]\nname = \"game\"\nversion = \"0.1.0\"\nedition = \"2021\"\n[dependencies]\nmy_helper = { path = \"../helper\" }\n").unwrap();
        scaffold(tmp.path()).unwrap();
        let module = tmp.path().join("src/postprocessing/mod.rs");
        fs::write(&module, "// my own native effects").unwrap();
        scaffold(tmp.path()).unwrap();
        assert_eq!(
            fs::read_to_string(&module).unwrap(),
            "// my own native effects"
        );
        let dir = prepare_editor(tmp.path()).unwrap();
        let manifest: toml_edit::DocumentMut = fs::read_to_string(dir.join("Cargo.toml"))
            .unwrap()
            .parse()
            .unwrap();
        assert_eq!(
            manifest["dependencies"]["my_helper"]["path"].as_str(),
            tmp.path()
                .canonicalize()
                .unwrap()
                .join("../helper")
                .to_str()
        );
        assert!(manifest["dependencies"]["enigma-engine"]["path"]
            .as_str()
            .is_some());
    }

    #[test]
    fn generated_editor_refuses_to_overwrite_handwritten_files() {
        let tmp = tempfile::tempdir().unwrap();
        fs::write(
            tmp.path().join("Cargo.toml"),
            "[package]\nname = \"game\"\nversion = \"0.1.0\"\n",
        )
        .unwrap();
        scaffold(tmp.path()).unwrap();
        let dir = tmp.path().join(".enigma/editor");
        fs::create_dir_all(dir.join("src")).unwrap();
        fs::write(dir.join("src/main.rs"), "fn main() { println!(\"mine\"); }").unwrap();
        assert!(prepare_editor(tmp.path()).is_err());
        assert!(!dir.join("Cargo.toml").exists());
    }
}
